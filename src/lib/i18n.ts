export const DICTS: Record<Lang, Dict> = { ja, en, zh, ko, th, es, fr, de }

export function translate(lang: Lang, key: string): string {
  return DICTS[lang][key] ?? DICTS.ja[key] ?? key
}

export const LangContext = createContext<Lang>('ja')

export function useLang(): { lang: Lang; t: (key: string) => string } {
  const lang = useContext(LangContext)
  return { lang, t: (key: string) => translate(lang, key) }
}
